"""Admission tests proving why a proposed repair direction is feasible."""

from __future__ import annotations

from typing import Any

from .catalog import get_domain_pack
from .evaluator import evaluate_submission, oracle_submission
from .injector import apply_patch
from .models import Outcome


def _get_path(document: dict[str, Any], path: str) -> Any:
    value: Any = document
    for part in path.split("."):
        value = value[part]
    return value


def assess_direction_feasibility(case: dict[str, Any]) -> dict[str, Any]:
    """Prove structural necessity, minimal repairability, and closure per atom.

    These checks run before any M3 surface rewrite. They do not claim empirical
    domain validity; they establish that the synthesized semantic contract is
    internally executable and that declared shortcuts cannot count as success.
    """

    pack = get_domain_pack(case["provenance"]["gold_project_id"])
    by_id = {flaw.flaw_id: flaw for flaw in pack.flaws}
    accepted_patch = case["oracle"]["canonical_reference_patch"]
    reports: list[dict[str, Any]] = []

    for active in case["oracle"]["revision_opportunities"]:
        flaw = by_id[active["opportunity_id"]]
        other_patch = {
            path: value
            for path, value in accepted_patch.items()
            if path != flaw.target_slot
        }
        after_other_repairs = apply_patch(case["flawed_state"], other_patch)
        target_only = apply_patch(
            case["flawed_state"], {flaw.target_slot: flaw.gold_value}
        )
        unchanged_paths = [
            path
            for path in case["oracle"]["construction_preserved_slots"]
            if _get_path(target_only, path) != _get_path(case["flawed_state"], path)
        ]

        shortcut_failures: list[str] = []
        for shortcut in flaw.forbidden_shortcuts:
            submission = oracle_submission(case)
            submission["actions"] = [shortcut]
            result = evaluate_submission(case, submission)
            if result.outcome is not Outcome.SHORTCUT_SUCCESS:
                shortcut_failures.append(shortcut)

        contract = case["oracle"]["opportunity_contracts"][flaw.target_slot]
        rejected_equivalent_operations: list[str] = []
        for option in contract["accepted_operations"]:
            submission = oracle_submission(case)
            submission["patch"].pop(flaw.target_slot)
            submission["repair_operations"][flaw.target_slot] = option
            result = evaluate_submission(case, submission)
            if not result.success:
                rejected_equivalent_operations.append(option["operation"])

        accepted_counterfactuals: list[str] = []
        for alternative in contract["rejected_alternatives"]:
            submission = oracle_submission(case)
            submission["patch"].pop(flaw.target_slot)
            submission["repair_operations"][flaw.target_slot] = {
                "operation": alternative["operation"],
                "parameters": {},
            }
            result = evaluate_submission(case, submission)
            if result.success:
                accepted_counterfactuals.append(alternative["operation"])

        evidence_alignment = all(
            evidence.supports_slot == flaw.target_slot for evidence in flaw.evidence
        )
        report = {
            "flaw_id": flaw.flaw_id,
            "direction": flaw.direction,
            "target_slot": flaw.target_slot,
            "causal_justification": flaw.rationale,
            "necessity_test": {
                "passed": (
                    _get_path(after_other_repairs, flaw.target_slot) == flaw.flawed_value
                    and after_other_repairs != case["gold_state"]
                ),
                "meaning": "Repairing every other atom still leaves this invariant violated.",
            },
            "feasible_repair_test": {
                "passed": (
                    _get_path(target_only, flaw.target_slot) == flaw.gold_value
                    and not unchanged_paths
                ),
                "meaning": "The target can be restored without changing preserved premises.",
            },
            "evidence_alignment_test": {
                "passed": evidence_alignment,
                "evidence_ids": [evidence.evidence_id for evidence in flaw.evidence],
                "meaning": "Each observation is generated by an audit tied to the target invariant.",
            },
            "alternative_rejection_tests": {
                "passed": not shortcut_failures and not accepted_counterfactuals,
                "tested_actions": list(flaw.forbidden_shortcuts),
                "tested_operations": [
                    item["operation"] for item in contract["rejected_alternatives"]
                ],
                "unexpectedly_accepted_actions": shortcut_failures,
                "unexpectedly_accepted_operations": accepted_counterfactuals,
            },
            "repair_equivalence_test": {
                "passed": not rejected_equivalent_operations,
                "accepted_operations": [
                    item["operation"] for item in contract["accepted_operations"]
                ],
                "unexpectedly_rejected": rejected_equivalent_operations,
                "invariants": list(contract["invariants"]),
            },
            "competing_nonrepair_test": {
                "passed": (
                    len(
                        {
                            item["analysis_tag"]
                            for item in contract["competing_nonrepairs"]
                        }
                    )
                    >= 2
                    and all(
                        item["analysis_tag"] != flaw.direction
                        and bool(item["exclusion_reason"])
                        for item in contract["competing_nonrepairs"]
                    )
                ),
                "analysis_tag": flaw.direction,
                "competing_nonrepairs": contract["competing_nonrepairs"],
                "meaning": "The case records plausible edits that do not discharge the violated scientific obligation.",
            },
            "propagation_contract_test": {
                "passed": set(flaw.downstream_slots).issubset(
                    set(case["oracle"]["propagation_obligations"])
                ),
                "required": list(flaw.downstream_slots),
            },
        }
        report["passed"] = all(
            value["passed"]
            for key, value in report.items()
            if key.endswith("_test") or key.endswith("_tests")
        )
        reports.append(report)

    closure = apply_patch(case["flawed_state"], accepted_patch) == case["gold_state"]
    return {
        "case_id": case["case_id"],
        "control_degree": case["control_degree"],
        "directions": reports,
        "closure_test": {
            "passed": closure,
            "meaning": "Applying all admitted minimal repairs reconstructs the valid state.",
        },
        "passed": closure and all(report["passed"] for report in reports),
    }
